#!/usr/bin/env bash
# Verify the cohort tree, and that the files added to it for Gate 3 have not drifted from the Ghost Gate
# repository they were copied from.
#
# The end-to-end harness lives inside the cohort (integration_tests/), so exercising the Ghost Gate template
# on a real localnet means adding files to the cohort tree. Those additions are vendored copies plus three
# edits, and this script is what keeps that honest:
#
#   1. both vendored templates' src/lib.rs are byte-identical to their ghost-gate/templates originals
#   2. the qualification rules are byte-identical to ghost-gate/crates/ghost-gate-core/src/lib.rs
#   3. the patched cohort differs from the pristine reference in exactly three accounted-for ways:
#        - the files the two documented patches touch: docs/wallet-mvp.patch and
#          docs/ghsa-empty-proof.patch (upstream GHSA-pp4v-v773-9qxg)
#        - Gate 3's integration additions, listed explicitly below
#        - build-script output (crates/template_builtin's compiled templates and their target dirs), which
#          is generated by building the cohort, not source
#      Anything else is a failure.
#
# Run it after touching the cohort tree, and before quoting the cohort's provenance as evidence.
#
# Usage: scripts/check_gate3_integration.sh
set -uo pipefail

WORKSPACE="${WORKSPACE:-/mnt/d/Codex/ghost-gate-workspace}"
COHORT="${COHORT:-$WORKSPACE/_ootle-v042-ghost-gate}"
REFERENCE="${REFERENCE:-$WORKSPACE/tari-ootle-v0.42.0-reference}"
PATCHED="${PATCHED:-$WORKSPACE/tari-ootle-v0.42.0-ghost-gate}"
REPO="${REPO:-$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)}"

status=0
note() { printf '%s\n' "$*"; }
fail() {
  note "FAIL: $*"
  status=1
}

# ---------------------------------------------------------------------------------------------
# 1 + 2. the vendored copies
# ---------------------------------------------------------------------------------------------
note "=== the vendored copies match the Ghost Gate repository ==="
while IFS=: read -r src dst; do
  [ -z "$src" ] && continue
  if [ ! -f "$dst" ]; then
    fail "${dst#"$COHORT"/} is missing"
  elif cmp -s "$src" "$dst"; then
    note "  ok  ${dst#"$COHORT"/}"
  else
    fail "${dst#"$COHORT"/} differs from ${src#"$REPO"/}"
    diff -u "$src" "$dst" | head -20
  fi
done <<EOF
$REPO/templates/ghost_gate/src/lib.rs:$COHORT/integration_tests/src/templates/ghost_gate/src/lib.rs
$REPO/templates/ghost_gate_faucet/src/lib.rs:$COHORT/integration_tests/src/templates/ghost_gate_faucet/src/lib.rs
$REPO/crates/ghost-gate-core/src/lib.rs:$COHORT/integration_tests/src/ghost_gate_core/src/lib.rs
EOF

# ---------------------------------------------------------------------------------------------
# 3. the patched tree against the pristine one
# ---------------------------------------------------------------------------------------------
note
note "=== every difference from the pristine reference is accounted for ==="

# (a) the two documented patches: docs/wallet-mvp.patch and docs/ghsa-empty-proof.patch
is_patch_entry() {
  case "$1" in
    # wallet-mvp.patch
    Files\ *"/applications/tari_walletd/"* | Files\ *"/crates/wallet/sdk/"* | Files\ *"/utilities/traffic-sim/"*) return 0 ;;
    Only\ in\ *mvp_integration_tests.rs | Only\ in\ *minimum_value_promise_tests.rs) return 0 ;;
    Only\ in\ *"/applications/tari_walletd/src/handlers: accounts"*) return 0 ;;
    # ghsa-empty-proof.patch (upstream 965e0bc6f, GHSA-pp4v-v773-9qxg)
    Files\ *"/crates/engine/src/runtime/tracker_auth.rs"* | Files\ *"/crates/engine/tests/access_rules.rs"* | Files\ *"/crates/engine_types/src/proof.rs"* | Files\ *"/crates/engine_types/src/resource_container.rs"*) return 0 ;;
    Only\ in\ *": .git"*) return 0 ;; # the pristine tree keeps its clone
    *) return 1 ;;
  esac
}

# (b) Gate 3's additions to the harness, each named
is_gate3_entry() {
  case "$1" in
    Files\ *"/integration_tests/Cargo.toml"* | Files\ *"/integration_tests/src/lib.rs"* | Files\ *"/integration_tests/tests/steps/mod.rs"*) return 0 ;;
    Files\ *"/Cargo.lock"*) return 0 ;; # the cohort lockfile gains the vendored core as a path package
    Only\ in\ *"/integration_tests/src: ghost_gate_core"* | Only\ in\ *"/integration_tests/src/templates: ghost_gate"* | Only\ in\ *"/integration_tests/src/templates: ghost_gate_faucet"* | Only\ in\ *"/integration_tests/tests/steps: ghost_gate.rs"* | Only\ in\ *"/integration_tests/tests/features: ghost_gate.feature"*) return 0 ;;
    *) return 1 ;;
  esac
}

# (c) build-script output
is_build_output() {
  case "$1" in
    Only\ in\ *"/crates/template_builtin/compiled: "*) return 0 ;;
    Only\ in\ *"/web_ui: dist"*) return 0 ;; # the indexer, validator and walletd web UIs, built by their build scripts
    # Every wasm template in the cohort is its own cargo workspace, so building any of them (the builtin
    # templates, the harness's own, the engine's test templates) leaves a target/ and a Cargo.lock behind.
    Only\ in\ *"/templates/"*": target"* | Only\ in\ *"/templates/"*": Cargo.lock"*) return 0 ;;
    # cucumber writes a JUnit report and a temp directory beside the features
    Only\ in\ *"/integration_tests: cucumber-output-junit.xml"* | Only\ in\ *"/integration_tests/tests: temp"*) return 0 ;;
    Only\ in\ *"/reference/.git"*) return 0 ;;
    *) return 1 ;;
  esac
}

patch_count=0
gate3_count=0
build_count=0
other_count=0
while IFS= read -r line; do
  [ -z "$line" ] && continue
  if is_patch_entry "$line"; then
    patch_count=$((patch_count + 1))
  elif is_gate3_entry "$line"; then
    gate3_count=$((gate3_count + 1))
  elif is_build_output "$line"; then
    build_count=$((build_count + 1))
  else
    other_count=$((other_count + 1))
    note "  unexplained: $line"
  fi
done < <(diff -rq "$REFERENCE" "$PATCHED" 2>/dev/null)

note "  documented patches (wallet-mvp + ghsa-empty-proof): $patch_count entries"
note "  Gate 3 integration additions:             $gate3_count entries"
note "  cohort build-script output:               $build_count entries"
if [ "$other_count" -gt 0 ]; then
  fail "$other_count unexplained divergence(s) between the reference and the patched cohort"
else
  note "  no unexplained divergence"
fi

# ---------------------------------------------------------------------------------------------
# the patch itself
# ---------------------------------------------------------------------------------------------
note
note "=== the wallet MVP patch is intact ==="
if [ -f "$REPO/docs/wallet-mvp.patch" ]; then
  note "  docs/wallet-mvp.patch: $(grep -c '^+++ ' "$REPO/docs/wallet-mvp.patch") files"
else
  fail "docs/wallet-mvp.patch is missing"
fi

note
if [ "$status" = 0 ]; then
  note "ALL CHECKS PASSED"
else
  note "CHECKS FAILED"
fi
exit "$status"